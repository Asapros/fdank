#define BASE_VADDR 0x400000

unsigned char code[128] = {};

int readlines() {
    Lexer lexer;
    lexer_init(&lexer, stdin);
    Token token;

    // while ((token = lexer_next_token(&lexer)).type != END) {
    //     print_token(token);
    //     printf("\n");
    // }
    // return;

    Parser parser;
    parser_init(&parser, lexer);
    Program program = parser_read_program(&parser);
    size_t size = 0;
    for (size_t i = 0; i < program.count; i++) {
        Statement statement = program.statements[i];

        SemanticAnalysis analysis = validate_statement(statement);
        if (!analysis.valid) {
            printf("Semantic analysis error: %s\n", analysis.description);
            return -1;
        }
        AssembledBytecode bytecode = generate_statement_bytecode(statement);
        memcpy(code + size, bytecode.binary, bytecode.size);
        size += bytecode.size;
    }
    return size;
}

int main() {
    size_t size = readlines();
    if (size == -1) {
        printf("Assembly terminated\n");
        return -1;
    }
    printf("generated bytecode: ");
    for (int i = 0; i < size; i++) {
        printf("%02x ", code[i]);
    }
    printf("\n");
    Elf64_Ehdr ehdr = {
        .e_ident = {
            0x7f, 'E', 'L', 'F',
            ELFCLASS64,
            ELFDATA2LSB,
            EV_CURRENT,
            ELFOSABI_SYSV
        },
        .e_type      = ET_EXEC,
        .e_machine   = EM_X86_64,
        .e_version   = EV_CURRENT,
        .e_entry     = BASE_VADDR + sizeof(Elf64_Ehdr) + sizeof(Elf64_Phdr),
        .e_phoff     = sizeof(Elf64_Ehdr),
        .e_shoff     = 0,
        .e_flags     = 0,
        .e_ehsize    = sizeof(Elf64_Ehdr),
        .e_phentsize = sizeof(Elf64_Phdr),
        .e_phnum     = 1,
        .e_shentsize = 0,
        .e_shnum     = 0,
        .e_shstrndx  = SHN_UNDEF
    };

    Elf64_Phdr phdr = {
        .p_type   = PT_LOAD,
        .p_flags  = PF_R | PF_X,
        .p_offset = 0,
        .p_vaddr  = BASE_VADDR,
        .p_paddr  = 0,
        .p_filesz = sizeof(Elf64_Ehdr) + sizeof(Elf64_Phdr) + size,
        .p_memsz  = sizeof(Elf64_Ehdr) + sizeof(Elf64_Phdr) + size,
        .p_align  = 0x1000
    };

    FILE *file = fopen("bin/a.out", "wb");

    fwrite(&ehdr, sizeof(ehdr), 1, file);
    fwrite(&phdr, sizeof(phdr), 1, file);
    fwrite(code, size, 1, file);

    fclose(file);


    return 0;
}
